from PIL import Image
from pypdf import PdfReader

def scan_report(file):

    if file is None:
        return "Please upload a medical report first."

    filename = file.lower()

    try:
        # Read PDF
        if filename.endswith(".pdf"):

            reader = PdfReader(file)

            extracted_text = ""

            for page in reader.pages:
                extracted_text += page.extract_text() or ""

            if not extracted_text.strip():
                return (
                    "No readable text was found in this PDF. "
                    "It may be a scanned document. "
                    "Please upload a clear JPG or PNG image instead."
                )

        # Read image using OCR
        elif filename.endswith((".png", ".jpg", ".jpeg")):

            image = Image.open(file)

            extracted_text = pytesseract.image_to_string(image)

        else:
            return "Unsupported file. Please upload a PDF, JPG or PNG."

        # Find relevant medical information
        lines = extracted_text.splitlines()

        keywords = ["glucose", "blood sugar", "hba1c", "a1c"]

        results = []

        for line in lines:
            if any(word in line.lower() for word in keywords):
                results.append(line.strip())

        if results:
            findings = "\n".join(
                [f"- {item}" for item in results]
            )
        else:
            findings = "No glucose or HbA1c references were identified."

        return f"""
## 📄 Report Extraction Complete!

### Possible glucose and HbA1c references

{findings}

### Extracted report text

{extracted_text[:4000]}

---

**Important:** This is automated text extraction, not medical interpretation.
Please verify all extracted values, units and reference ranges
against your original report and consult a healthcare professional.
"""

    except Exception as e:
        return f"Unable to read the report. Error: {str(e)}"


